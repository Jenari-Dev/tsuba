#!/usr/bin/env python3
"""Regenerate docs/THIRD-PARTY-LICENSES.md from Cargo.lock (needs `cargo metadata`, offline is fine)."""
import json, subprocess, sys, os

root = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
meta = json.loads(subprocess.check_output(["cargo", "metadata", "--format-version", "1", "--locked", "--offline"], cwd=root))
ws = set(meta["workspace_members"])
pkgs = [p for p in meta["packages"] if p["id"] not in ws]
by_lic = {}
for p in sorted(pkgs, key=lambda p: (p["name"], p["version"])):
    lic = (p.get("license") or p.get("license_file") or "see crate").strip()
    by_lic.setdefault(lic, []).append(p)

out = ["# Third-party licences", "",
       "Tsuba is licensed GPL-2.0-or-later (see `LICENSE`). It is built from the components below, each under its own licence.",
       "This file is generated by `tools/gen-third-party.py`; do not edit it by hand.", "",
       "## System libraries (used, not bundled)", "",
       "- Qt 6 (Base, Declarative, SVG): LGPL-3.0 / GPL-2.0-or-later, https://www.qt.io",
       "- KDE Frameworks 6 (KI18n and its dependencies): LGPL-2.1-or-later, https://kde.org",
       "- qqc2-breeze-style: LGPL-2.1-or-later / GPL-2.0-or-later, https://invent.kde.org/plasma/qqc2-breeze-style",
       "- PipeWire (libpipewire): MIT, https://pipewire.org",
       "- PulseAudio client library: LGPL-2.1-or-later, https://www.freedesktop.org/wiki/Software/PulseAudio/",
       "- Roboto (UI font, installed as a system font): Apache-2.0, https://github.com/googlefonts/roboto", "",
       f"## Rust crates ({len(pkgs)})", ""]
for lic in sorted(by_lic):
    out.append(f"### {lic}")
    out.append("")
    out.append(", ".join(f"{p['name']} {p['version']}" for p in by_lic[lic]))
    out.append("")
out += ["## Not included", "",
        "Tsuba contains no code, artwork, fonts, firmware or data from Razer Inc. Device drawings are Tsuba's own.", ""]
open(os.path.join(root, "docs", "THIRD-PARTY-LICENSES.md"), "w").write("\n".join(out))
print("wrote docs/THIRD-PARTY-LICENSES.md:", len(pkgs), "crates,", len(by_lic), "licence expressions", file=sys.stderr)
